def allocate():
    """중요도(영역 별점) → 최신 연도 순으로 정렬해 11문항씩 1~6회에 배정. 회차 안에서는 2점 → 4점 순."""
    def year(k): return int(k[:4])
    ranked = sorted(EXAM_ITEMS, key=lambda t: (-AREAS[t[2]]['stars'], -year(t[0]), t[0]))
    alloc = {}
    for i in range(6):
        chunk = ranked[i * 11:(i + 1) * 11]
        chunk.sort(key=lambda t: (t[1], {'C': 0, 'D': 1, 'F': 2, 'E': 3, 'G': 4, 'B': 5, 'A': 6}[t[2]], -year(t[0])))
        for j, t in enumerate(chunk):
            alloc[t[0]] = (i + 1, j + 1)
    return alloc


